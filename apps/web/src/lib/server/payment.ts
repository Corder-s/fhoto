import crypto from 'crypto';

/**
 * REEPY Payment Gateway Service Configuration & Utilities
 *
 * Supports:
 * 1. Razorpay Standard Checkout (orders API, checkout options, signature verification)
 * 2. Secure Development Sandbox (test mode when live keys are unset)
 */

export interface RazorpayCredentials {
  keyId: string;
  keySecret: string;
  webhookSecret?: string;
  isConfigured: boolean;
}

/**
 * Retrieve and validate Razorpay credentials from environment variables.
 * Checks RAZORPAY_KEY_ID / NEXT_PUBLIC_RAZORPAY_KEY_ID and
 * RAZORPAY_KEY_SECRET / PAYMENT_PROVIDER_SECRET_KEY.
 */
export function getRazorpayCredentials(): RazorpayCredentials {
  const keyId =
    process.env.RAZORPAY_KEY_ID ||
    process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID ||
    '';

  const keySecret =
    process.env.RAZORPAY_KEY_SECRET ||
    process.env.PAYMENT_PROVIDER_SECRET_KEY ||
    '';

  const webhookSecret =
    process.env.RAZORPAY_WEBHOOK_SECRET ||
    process.env.PAYMENT_PROVIDER_WEBHOOK_SECRET ||
    '';

  const isConfigured = Boolean(
    keyId &&
    keySecret &&
    !keyId.includes('placeholder') &&
    !keySecret.includes('placeholder')
  );

  return { keyId, keySecret, webhookSecret, isConfigured };
}

export interface CreateOrderParams {
  amountInPaise: number;
  currency: string;
  receipt: string;
  notes?: Record<string, string>;
}

export interface GatewayOrderResult {
  orderId: string;
  amount: number;
  currency: string;
  provider: 'razorpay' | 'dev_sandbox';
  isSandbox: boolean;
  rawResponse?: any;
}

/**
 * Create an order with Razorpay or generate a development sandbox order.
 */
export async function createGatewayOrder(params: CreateOrderParams): Promise<GatewayOrderResult> {
  const creds = getRazorpayCredentials();

  if (creds.isConfigured) {
    const authHeader = Buffer.from(`${creds.keyId}:${creds.keySecret}`).toString('base64');
    const response = await fetch('https://api.razorpay.com/v1/orders', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Basic ${authHeader}`,
      },
      body: JSON.stringify({
        amount: params.amountInPaise,
        currency: params.currency || 'INR',
        receipt: params.receipt,
        notes: params.notes || {},
      }),
    });

    if (!response.ok) {
      const errBody = await response.text();
      console.error('[Razorpay Order Creation Failed]', response.status, errBody);
      throw new Error(`Razorpay gateway rejected order creation: ${errBody}`);
    }

    const orderData = await response.json();
    return {
      orderId: orderData.id,
      amount: orderData.amount,
      currency: orderData.currency,
      provider: 'razorpay',
      isSandbox: false,
      rawResponse: orderData,
    };
  }

  // Development Sandbox Order Generation
  const sandboxOrderId = `order_dev_${Date.now()}_${Math.random().toString(36).substring(2, 9)}`;
  return {
    orderId: sandboxOrderId,
    amount: params.amountInPaise,
    currency: params.currency || 'INR',
    provider: 'dev_sandbox',
    isSandbox: true,
  };
}

export interface VerifySignatureParams {
  orderId: string;
  paymentId: string;
  signature: string;
}

/**
 * Cryptographically verify Razorpay payment signature using HMAC SHA-256.
 * Signature formula: HMAC_SHA256(order_id + "|" + payment_id, secret) === signature
 */
export function verifyPaymentSignature(params: VerifySignatureParams): { isValid: boolean; error?: string } {
  const { orderId, paymentId, signature } = params;
  const creds = getRazorpayCredentials();

  if (!orderId || !paymentId || !signature) {
    return { isValid: false, error: 'Missing payment verification credentials (orderId, paymentId, or signature).' };
  }

  // 1. Live or Test Razorpay Gateway Verification
  if (creds.isConfigured) {
    try {
      const expectedSignature = crypto
        .createHmac('sha256', creds.keySecret)
        .update(`${orderId}|${paymentId}`)
        .digest('hex');

      const sigBuf = Buffer.from(signature, 'utf8');
      const expectedBuf = Buffer.from(expectedSignature, 'utf8');

      if (sigBuf.length !== expectedBuf.length) {
        return { isValid: false, error: 'Razorpay payment signature mismatch.' };
      }

      const isMatch = crypto.timingSafeEqual(sigBuf, expectedBuf);
      return isMatch ? { isValid: true } : { isValid: false, error: 'Razorpay payment signature mismatch.' };
    } catch (err: any) {
      return { isValid: false, error: `Signature verification exception: ${err?.message}` };
    }
  }

  // 2. Development Sandbox Verification
  // In sandbox, check for sandbox signature generated by client or server
  if (orderId.startsWith('order_dev_') || paymentId.startsWith('pay_dev_')) {
    const sandboxSecret = 'reepy_dev_sandbox_secret_2026';
    const expectedSandboxSig = crypto
      .createHmac('sha256', sandboxSecret)
      .update(`${orderId}|${paymentId}`)
      .digest('hex');

    if (signature === expectedSandboxSig || signature.startsWith('sig_dev_sandbox_')) {
      return { isValid: true };
    }
  }

  return { isValid: false, error: 'Unrecognized payment provider or invalid signature.' };
}

/**
 * Generate sandbox signature for development test mode.
 */
export function generateSandboxSignature(orderId: string, paymentId: string): string {
  const sandboxSecret = 'reepy_dev_sandbox_secret_2026';
  return crypto
    .createHmac('sha256', sandboxSecret)
    .update(`${orderId}|${paymentId}`)
    .digest('hex');
}

/**
 * Verify incoming webhook signature against configured webhook secret.
 */
export function verifyWebhookSignature(rawBody: string, signature: string | null): boolean {
  if (!signature) return false;
  const creds = getRazorpayCredentials();
  const secret = creds.webhookSecret;

  if (!secret || secret.includes('placeholder')) {
    // If webhook secret is not set, reject in production
    if (process.env.NODE_ENV === 'production') return false;
    return true;
  }

  try {
    const expectedSignature = crypto
      .createHmac('sha256', secret)
      .update(rawBody)
      .digest('hex');

    const sigBuf = Buffer.from(signature, 'utf8');
    const expectedBuf = Buffer.from(expectedSignature, 'utf8');

    if (sigBuf.length !== expectedBuf.length) {
      return false;
    }

    return crypto.timingSafeEqual(sigBuf, expectedBuf);
  } catch {
    return false;
  }
}
